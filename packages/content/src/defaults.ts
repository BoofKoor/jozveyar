/** «سیاه‌سفید {نرخ} تومان»، و وقتی یکرو نرخ دیگری دارد «… در دورو و {نرخ_یکرو} تومان در یکرو». */
function rate(rates: ContentFacts['rates'], color: 'bw' | 'color'): string {
  const [double, single] = color === 'bw' ? [rates.bw, rates.bwSingle] : [rates.color, rates.colorSingle];
  const name = color === 'bw' ? 'نرخ_سیاه_سفید' : 'نرخ_رنگی';
  return double === single ? `{${name}} تومان` : `{${name}} تومان در دورو و {${name}_یکرو} تومان در یکرو`;
}

