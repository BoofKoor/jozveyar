/** متن پیش‌فرض یک نوع؛ نسخه‌ای تازه، تا کسی نتواند ثابت را دست بزند. */
export function defaultContent<K extends ContentKind>(kind: K, facts: ContentFacts = SEED_FACTS): ContentByKind[K] {
  const copy = <T>(value: T): T => structuredClone(value);
  const table: { [P in ContentKind]: () => ContentByKind[P] } = {
    home: () => copy(HOME),
    faq: () => faq(facts),
    terms: () => copy(TERMS),
    privacy: () => copy(PRIVACY),
    about: () => copy(ABOUT),
    contact: () => copy(CONTACT),
  };
  return table[kind]() as ContentByKind[K];
}
