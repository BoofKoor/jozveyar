import { StaticPage } from '../../components/StaticPage';
import { siteFacts } from '../../lib/server/siteFacts';
import { STATIC_PAGES, pageDate, pageMetadata } from '../../lib/staticPages';

/** مثل صفحهٔ اصلی ISR ۶۰ ثانیه: روز کاری تحویل و نگهداری فایل از `settings` (`lib/server/siteFacts.ts`). */
export const revalidate = 60;

